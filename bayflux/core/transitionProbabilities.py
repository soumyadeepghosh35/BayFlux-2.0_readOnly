"""
Transition Probability Calculation Module for BayFlux ACHR Sampling.

This module implements transition probability calculations for the BayFlux Bayesian 
flux analysis framework using Artificial Centering Hit-and-Run (ACHR) sampling with 
Generalized Metropolis-Hastings (GMH) acceptance criteria.

The module provides optimized numerical methods for computing transition probability 
matrices in parallel MCMC sampling scenarios, with particular attention to numerical 
stability and computational efficiency through Numba JIT compilation.

Key Features:
- Symmetric proposal handling for ACHR sampling
- Numerically stable log-likelihood ratio computations
- GMH-based transition matrix construction
- JIT compilation for high-performance execution
- Robust handling of extreme likelihood values

The implementation follows the theoretical framework described in:
- Generalized Metropolis-Hastings sampling theory
- ACHR sampling methodology for constraint-based systems
- Numerical stability practices for MCMC implementations

Dependencies:
- NumPy for array operations and mathematical functions
- Numba for JIT compilation and performance optimization
- SciPy for statistical distributions (imported but preserved for potential use)

Author: BayFlux Development Team
License: See license.txt
Version: 2.0
"""

import numpy as np
from numba import jit
import numba as nb
from typing import Tuple

# Global constants for numerical stability and performance
MAX_LOG_RATIO = 700.0  # Maximum log ratio to prevent overflow in exp() calculations
MIN_LOG_RATIO = -700.0  # Minimum log ratio to prevent underflow in exp() calculations  
NUMERICAL_STABILITY_EPSILON = 1e-12  # Small epsilon for numerical stability corrections


@jit(nopython=True)
def calculateTransitionProbabilitiesBayflux(
    samplesTemp: np.ndarray, 
    likelihoods: np.ndarray, 
    numProposals: int
) -> np.ndarray:
    """
    Calculate transition probabilities for BayFlux ACHR sampling with symmetric proposals.
    
    This function computes the transition probability matrix for a Generalized 
    Metropolis-Hastings (GMH) sampler operating on flux vectors generated through 
    Artificial Centering Hit-and-Run (ACHR) sampling. The implementation assumes 
    symmetric proposal distributions where q(x_j|x_i) = q(x_i|x_j), which 
    significantly simplifies the acceptance ratio calculations.
    
    The algorithm follows the GMH framework where transition probabilities are 
    computed based on likelihood ratios and the assumption of uniform sampling 
    within the feasible flux space. Special attention is given to numerical 
    stability when handling extreme likelihood values.

    Parameters
    ----------
    samplesTemp : np.ndarray
        Shape (numProposals + 1, n_reactions). Array containing flux vectors where:
        - Row 0: Current flux state (x_i)
        - Rows 1 to numProposals: Proposal flux states from parallel ACHR workers (x_j)
        Each column represents a different metabolic reaction flux.
    likelihoods : np.ndarray
        Shape (numProposals + 1,). Log-likelihood values corresponding to each 
        flux vector in samplesTemp. These represent the log P(data|flux) values 
        computed from experimental observations.
    numProposals : int
        Number of proposal states generated by parallel workers, excluding the 
        current state. Must be positive integer.

    Returns
    -------
    np.ndarray
        Shape (numProposals + 1, numProposals + 1). Transition probability matrix A 
        where A[i,j] represents the probability of transitioning from state i to 
        state j. Matrix properties:
        - Each row sums to 1.0 (stochastic matrix)
        - Diagonal elements represent self-transition probabilities
        - Off-diagonal elements represent inter-state transition probabilities
        - Follows detailed balance condition for MCMC convergence

    Notes
    -----
    The transition probability calculation follows these key steps:
    
    1. **Acceptance Ratio Computation**: For symmetric proposals, the acceptance 
       ratio R(i,j) = min(1, P(x_j)/P(x_i)) = min(1, exp(log_likelihood[j] - log_likelihood[i]))
    
    2. **Numerical Stability**: Log ratios are clamped to [-700, 700] to prevent 
       numerical overflow/underflow in exponential calculations.
    
    3. **GMH Matrix Construction**: Transition matrix elements are set as:
       - A[i,j] = R(i,j) for i ≠ j (acceptance probability)
       - A[i,i] = 1 - Σ(A[i,j]) for j ≠ i (self-transition probability)
    
    4. **Matrix Correction**: If diagonal elements become negative due to numerical 
       errors, the off-diagonal elements are rescaled proportionally.

    The function is JIT-compiled with Numba for high-performance execution in 
    production MCMC sampling loops.

    
    Raises
    ------
    ValueError
        If samplesTemp and likelihoods do not have the same non-zero length.
        The check is performed inside the compiled kernel, so it costs one
        integer comparison per call.

    Notes
    -----
    The function is JIT-compiled and may also raise Numba-specific exceptions
    for invalid array dtypes or for numerical failures in extreme cases.
    
    See Also
    --------
    steadyStateDistribution : Computes equilibrium distribution from transition matrix
    MCMCACHRSampler : Main sampler class that uses this function
    """
    # Ensure numerical stability by converting to float64 precision
    likelihoods = np.asarray(likelihoods, dtype=np.float64)
    
    # DEVELOPER: Prior probabilities integration point
    # This commented section preserves the framework for incorporating prior 
    # distributions in future versions. Currently, uniform priors are assumed.
    # priors = np.asarray(priors, dtype=np.float64)
    # log_posteriors = likelihoods + priors

    numStates = samplesTemp.shape[0]

    # One likelihood per flux vector, and at least one state to move between.
    # Without this guard a mismatch reads past the end of likelihoods, which
    # in nopython mode is unchecked and returns silent garbage.
    if numStates == 0 or likelihoods.shape[0] != numStates:
        raise ValueError("samplesTemp and likelihoods must have the same non-zero length")
    
    # Initialize acceptance ratio matrix R(i,j) = min(1, P(j)/P(i))
    # For symmetric proposals, this simplifies to likelihood ratio only
    acceptanceRatios = np.zeros((numStates, numStates), dtype=np.float64)
    
    # Compute pairwise acceptance ratios with numerical stability measures
    for i in range(numStates):
        for j in range(numStates):
            if i != j:
                # Calculate log-likelihood ratio for acceptance probability
                logRatio = likelihoods[j] - likelihoods[i]
                
                # Apply numerical stability bounds to prevent overflow/underflow
                if logRatio > MAX_LOG_RATIO:
                    # If j is much more likely than i, accept with probability 1
                    acceptanceRatios[i, j] = 1.0
                elif logRatio < MIN_LOG_RATIO:
                    # If j is much less likely than i, reject (probability 0)
                    acceptanceRatios[i, j] = 0.0
                else:
                    # Standard Metropolis acceptance ratio: min(1, exp(log_ratio))
                    expRatio = np.exp(logRatio)
                    acceptanceRatios[i, j] = min(1.0, expRatio)

    # Construct GMH transition matrix following detailed balance condition
    transitionMatrix = np.zeros((numStates, numStates), dtype=np.float64)
    
    for i in range(numStates):
        offDiagonalSum = 0.0
        
        # Set off-diagonal transition probabilities (inter-state transitions)
        for j in range(numStates):
            if i != j:
                transitionMatrix[i, j] = acceptanceRatios[i, j]
                offDiagonalSum += transitionMatrix[i, j]
        
        # Set diagonal element to ensure row sums to 1 (stochastic property)
        transitionMatrix[i, i] = 1.0 - offDiagonalSum
        
        # Numerical stability correction for negative diagonal elements
        # This can occur due to floating-point precision errors
        if transitionMatrix[i, i] < 0.0:
            if offDiagonalSum > 1.0:
                # Rescale off-diagonal elements proportionally to sum to (1 - epsilon)
                scalingFactor = (1.0 - NUMERICAL_STABILITY_EPSILON) / offDiagonalSum
                for j in range(numStates):
                    if i != j:
                        transitionMatrix[i, j] *= scalingFactor
                
                # Recompute diagonal element after rescaling
                transitionMatrix[i, i] = 1.0 - np.sum(transitionMatrix[i, :]) + transitionMatrix[i, i]
            else:
                # Set diagonal to zero if off-diagonal sum is invalid
                transitionMatrix[i, i] = 0.0

    return transitionMatrix





